"""Generate the 1° corrected magnetic latitude table (AACGM-v2, 110 km).

Run once per IGRF release, outside the project environment, because aacgmv2 is
not a backend dependency:

    python3 -m venv /tmp/aacgm && /tmp/aacgm/bin/pip install aacgmv2
    /tmp/aacgm/bin/python backend/tools/generate_aacgm_table.py

It writes src/aurora_backend/astronomy/aacgm_table.py: signed magnetic latitude
in hundredths of a degree for latitudes -90..90 and longitudes -180..179, as
zlib-compressed little-endian int16, with -32768 where AACGM is undefined.
The table is a Python module so the hosted bundle (Python files only) carries it.
"""

import base64
import datetime
import math
import struct
import sys
import textwrap
import zlib
from pathlib import Path

import aacgmv2  # type: ignore[import-not-found]

EPOCH = datetime.datetime(2026, 11, 1)
HEIGHT_KM = 110.0
UNDEFINED = -32768
TARGET = Path(__file__).resolve().parents[1] / "src/aurora_backend/astronomy/aacgm_table.py"


def main() -> None:
    values = []
    for lat in range(-90, 91):
        lats = [float(lat)] * 360
        lons = [float(lon) for lon in range(-180, 180)]
        mlat, _, _ = aacgmv2.convert_latlon_arr(lats, lons, HEIGHT_KM, EPOCH, method_code="G2A")
        for value in mlat:
            values.append(UNDEFINED if math.isnan(value) else round(float(value) * 100))
    raw = struct.pack(f"<{len(values)}h", *values)
    encoded = base64.b64encode(zlib.compress(raw, 9)).decode()
    lines = "\n".join(f'    "{line}"' for line in textwrap.wrap(encoded, 80))
    TARGET.write_text(
        '"""Generated by backend/tools/generate_aacgm_table.py; do not edit."""\n\n'
        f'MODEL = "AACGM-v2 {aacgmv2.__version__}, {HEIGHT_KM:g} km, epoch {EPOCH.date()}"\n'
        f"UNDEFINED = {UNDEFINED}\n"
        f"DATA = (\n{lines}\n)\n"
    )
    print(f"{TARGET}: {len(values)} cells, {len(encoded)} base64 chars", file=sys.stderr)


if __name__ == "__main__":
    main()
