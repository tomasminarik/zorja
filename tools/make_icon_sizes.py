#!/usr/bin/env python3
"""Make the 16 and 20 pt icon variants from the 24 pt icons in the asset catalog.

Figma shrinks an icon inside a button or chip but keeps its 1.75 stroke. Scaling the 24 pt
SVG in the app would thin the stroke to 1.17 pt (16) or 1.46 pt (20), so each size gets its
own SVG: same paths on the 24 grid, drawn at the smaller size with a thicker stroke that
renders at the original width. Icons drawn from outlines only (the crossed-out ones) have
no stroke to keep and get no variants.

It also writes IconGlyphInsets.swift: how far each glyph's ink sits inside its 24 pt frame,
which pills use to centre an icon and a label by eye.

Run from the repository root after changing an icon: python3 tools/make_icon_sizes.py
"""
import json
import re
from pathlib import Path

ICONS = Path("ios/Zorja/Assets.xcassets/Icon")
INSETS_SWIFT = Path("ios/Zorja/Presentation/IconGlyphInsets.swift")
SIZES = (16, 20)
GRID = 24


def variant(svg: str, size: int) -> str:
    scale = GRID / size
    svg = svg.replace(f'width="{GRID}" height="{GRID}"', f'width="{size}" height="{size}"', 1)
    return re.sub(
        r'stroke-width="([0-9.]+)"',
        lambda m: f'stroke-width="{float(m.group(1)) * scale:g}"',
        svg,
    )


def path_points(d: str):
    """Points along an SVG path: corners, and samples along cubic curves."""
    tokens = re.findall(r"[MLHVCZmlhvcz]|-?\d*\.?\d+(?:e-?\d+)?", d)
    x = y = start_x = start_y = 0.0
    index = 0
    command = "M"

    def number() -> float:
        nonlocal index
        index += 1
        return float(tokens[index - 1])

    while index < len(tokens):
        if re.match("[A-Za-z]", tokens[index]):
            command = tokens[index]
            index += 1
        if command in "Zz":
            x, y = start_x, start_y
            continue
        relative = command.islower()
        kind = command.upper()
        if kind in "ML":
            nx, ny = number(), number()
            x, y = (x + nx, y + ny) if relative else (nx, ny)
            if kind == "M":
                start_x, start_y = x, y
                command = "l" if relative else "L"
            yield x, y
        elif kind == "H":
            x = number() + (x if relative else 0)
            yield x, y
        elif kind == "V":
            y = number() + (y if relative else 0)
            yield x, y
        elif kind == "C":
            p = [number() for _ in range(6)]
            if relative:
                p = [v + (x if k % 2 == 0 else y) for k, v in enumerate(p)]
            curve = [(x, y), (p[0], p[1]), (p[2], p[3]), (p[4], p[5])]
            for step in range(1, 21):
                t = step / 20
                m = 1 - t
                weights = (m ** 3, 3 * m * m * t, 3 * m * t * t, t ** 3)
                yield tuple(sum(w * point[axis] for w, point in zip(weights, curve)) for axis in range(2))
            x, y = p[4], p[5]
        else:
            raise ValueError(f"unsupported path command {command}")


def glyph_insets(svg: str):
    """Ink distance from each edge of the 24 pt frame: top, leading, bottom, trailing."""
    boxes = []
    for attributes in re.findall(r"<path([^>]*)>", svg):
        d = re.search(r'd="([^"]*)"', attributes).group(1)
        width = re.search(r'stroke-width="([0-9.]+)"', attributes)
        half = float(width.group(1)) / 2 if width else 0
        boxes += [(px - half, py - half, px + half, py + half) for px, py in path_points(d)]
    return (
        min(b[1] for b in boxes),
        min(b[0] for b in boxes),
        GRID - max(b[3] for b in boxes),
        GRID - max(b[2] for b in boxes),
    )


def swift_name(name: str) -> str:
    """`ZorjaIcon` case for an asset name: calendar-add → calendarAdd, 3-nights → threeNights."""
    parts = name.replace("3-", "three-").split("-")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def write_insets(insets: dict) -> None:
    lines = [
        "// Generated by tools/make_icon_sizes.py from the icon SVGs. Do not edit.",
        "import SwiftUI",
        "",
        "extension ZorjaIcon {",
        "    /// How far the glyph's ink sits inside its 24 pt frame, at the 1.75 stroke.",
        "    var glyphInsets24: EdgeInsets {",
        "        switch self {",
    ]
    for name, (top, leading, bottom, trailing) in sorted(insets.items()):
        lines.append(
            f"        case .{swift_name(name)}: EdgeInsets(top: {top:.2f}, leading: {leading:.2f}, "
            f"bottom: {bottom:.2f}, trailing: {trailing:.2f})"
        )
    lines += ["        }", "    }", "}", ""]
    INSETS_SWIFT.write_text("\n".join(lines))


def main() -> None:
    insets = {}
    for imageset in sorted(ICONS.glob("*.imageset")):
        name = imageset.stem
        if re.search(r"-\d+$", name):
            continue
        source = imageset / f"{name}.svg"
        svg = source.read_text()
        insets[name] = glyph_insets(svg)
        if "stroke-width" not in svg:
            continue
        contents = json.loads((imageset / "Contents.json").read_text())
        for size in SIZES:
            target = ICONS / f"{name}-{size}.imageset"
            target.mkdir(exist_ok=True)
            (target / f"{name}-{size}.svg").write_text(variant(svg, size))
            contents["images"][0]["filename"] = f"{name}-{size}.svg"
            (target / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n")
    write_insets(insets)


if __name__ == "__main__":
    main()
